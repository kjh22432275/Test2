    // 1. 사용자가 입력한 5줄 조건에 문항 키워드가 직접 등장하면 최우선 가산점 부여
    for (const kw of q.keywords) {
      if (conditionTrimmed.includes(kw)) {
        score += 25;
      }
    }

    // 2. 성향 카테고리 매칭 가산점
    if (wantFactCheck && q.tags.includes('fact-check')) score += 18;
    if (wantDeepTheory && q.tags.includes('deep-theory')) score += 18;
    if (wantDexterity && q.tags.includes('dexterity')) score += 18;
    if (wantEthics && q.tags.includes('ethics')) score += 18;
    if (wantVulnerability && q.tags.includes('vulnerability')) score += 18;

